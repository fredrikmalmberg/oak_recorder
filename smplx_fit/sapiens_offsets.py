"""Measured offsets of Sapiens2 and WiLoR keypoints relative to the exact SMPL-X targets they are mapped to
(smplx_fit.joint_mapping), from synthetic renders. Documented, with the method, in README.md ("Sapiens keypoints vs SMPL-X
joints, measured on synthetic renders"); generated by smplx_fit.synth_render / synth_sapiens / synth_wilor / synth_analyze.

Offset = triangulated keypoint minus SMPL-X target, millimetres. Not applied anywhere in the fit yet. To correct a target,
subtract the offset from the Sapiens keypoint (or add it to the SMPL-X target when building the loss).

Hand offsets are in each hand's own frame (smplx_fit.data_loading.hand_frame: x = wrist -> middle MCP, y = z cross x,
z = palm normal from (index MCP - wrist) x (pinky MCP - wrist)), expressed in the LEFT-hand convention: for the right hand
negate the z component. Keys follow synth_analyze.HAND_NAMES (hand landmark ids 0..20 in MediaPipe order).
Body offsets are in a person frame (x right shoulder -> left shoulder, y pelvis -> neck, z = x cross y) and are only
the Sapiens ones; they vary with body shape and texture (std below), so they are not safe to apply as constants.

Values: mean over 9 render sets (6 textures/flat with the fit shape, 3 random shapes), each the median over 10 fitted poses
(+ both hands for the hand tables), 18 views per pose, male SMPL-X, take3 pose set (frames 300-650). *_STD is the std over the sets.

NOTES (read before using these):
- What the numbers say. Sapiens' hand wrist keypoint is ~15 mm proximal of the SMPL-X wrist joint, and its five MCP keypoints
  are 10-21 mm proximal (mean ~16 mm) and 4-12 mm along the palm normal. Wrist and MCPs are shifted together: the palm block
  is shifted ~15 mm toward the elbow and the palm length (wrist -> MCP) is within ~6 mm of SMPL-X's. PIP, DIP and fingertips
  are within ~5 mm of the SMPL-X joints, so the finger joints are roughly right in absolute terms. Which side of the hand the
  palm-normal component points to has NOT been checked (do not read it as dorsal or palmar). Probable cause: Sapiens places the
  wrist and knuckles as skin-surface landmarks, not at SMPL-X joint centres (not verified against its training definition).
- Consistency across conditions: wrist and MCP offsets vary by <= ~1 mm std over 6 textures/flat and 3 random body shapes (arm
  span 484-569 mm), so they are close to constants. T-pose renders show a smaller wrist offset (1-4 mm), so the offset is
  partly pose dependent: it was measured on fitted take3 poses.
- What the fit corrects (FIT_CORRECTED_LANDMARKS): the wrist and the five MCPs, nothing else. Do not correct PIP and beyond:
  they are already within ~5 mm and shifting them would push the finger chain off.
- Not corrected: body offsets (SAPIENS_BODY_OFFSET_MM). Elbows are stable (std ~1 mm) but shoulders (std 3-5 mm) and hip
  y/z (5-10 mm) depend on shape and texture; hip x (~34 mm, std 2) is a candidate for a later variant. The body-table wrist is
  not used: the body wrist and hand wrist (landmark 0) are the same fused point, corrected with the hand-frame value.
- Domain gap: measured on synthetic renders (generic clothes), not photos. The offsets have not been validated on real
  frames. On real data an unshifted fit already puts the SMPL-X wrist ~4 mm distal of the Sapiens wrist, and the earlier
  +23 mm MANO-wrist shift made elbows and wrists worse, so judge the corrected fit on residuals, not on the offsets themselves.
- Applied in smplx_fit.model.apply_sapiens_offsets (fit_take --sapiens-offsets): added on the SMPL-X side in the model's own
  hand frame (x wrist -> middle MCP, z palm normal, from the predicted wrist and index/middle/pinky MCP joints; frame
  detached), equivalent to subtracting the offset from the Sapiens target but with an exact frame.
"""

